import path from 'node:path';
import process from 'node:process';
import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { run, waitForExit } from './process-runner.ts';
import { createHash } from 'node:crypto';
import { workspaceRoot, cliRoot, harnessRoot } from './workspace-paths.ts';

const kind = process.argv[2];
if (kind !== 'harness' && kind !== 'cli') throw new Error('Usage: node scripts/pack-native.ts <harness|cli>');
const root = kind === 'harness' ? harnessRoot : cliRoot;
const binary = kind === 'harness' ? 'jynx-harness' : 'jynx-cli';
const executable = `${binary}${process.platform === 'win32' ? '.exe' : ''}`;
const source = path.join(root, 'target', 'release', executable);
const version = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8')).version;
const platform = process.platform === 'win32' ? 'windows' : process.platform === 'darwin' ? 'macos' : 'linux';
const artifactName = kind === 'harness' ? 'jynx-harness' : 'jynx-cli';
const releaseName = kind === 'harness' ? 'Jynx-Harness-Server' : 'Jynx-CLI-Only';
const releaseBase = `${releaseName}-v${version}-${platform}-${process.arch}`;
const name = `${releaseBase}.tar.gz`;
const dist = path.join(workspaceRoot, 'dist');
await access(source).catch(() => { throw new Error(`Build ${kind} first: ${source}`); });
await mkdir(dist, { recursive: true });
const manifest = { name: artifactName, version, platform, arch: process.arch, executable, license: 'GPL-3.0-only', source: `https://github.com/R3FStudio/Jynx/tree/v${version}` };
await writeFile(path.join(dist, `${releaseBase}.manifest.json`), `${JSON.stringify(manifest, null, 2)}\n`);
const tar = run('tar', ['-czf', path.join(dist, name), '-C', path.join(root, 'target', 'release'), executable, '-C', workspaceRoot, 'LICENSE', 'COPYRIGHT'], { cwd: root });
await waitForExit(tar, `${kind} archive`);
const digest = createHash('sha256').update(await readFile(path.join(dist, name))).digest('hex');
await writeFile(path.join(dist, `${name}.sha256`), `${digest}  ${name}\n`);
console.log(path.join(dist, name));
